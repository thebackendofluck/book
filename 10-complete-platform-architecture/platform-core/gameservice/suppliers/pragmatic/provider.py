"""
suppliers/pragmatic/provider.py
--------------------------------
Pragmatic Play — Slots + Live Casino seamless-wallet integration.

Integration model
-----------------
Pragmatic Play uses a seamless-wallet integration. The operator provides
a wallet endpoint that Pragmatic calls for every transaction. Game launches
are initiated by the operator using a signed URL with an operator-specific
secret key.

Quirks and gotchas
------------------
1. **MD5 hash authentication** — Pragmatic signs every callback using MD5
   of (sorted params + key). The operator MUST verify this hash on every
   request. Failing to verify opens the endpoint to fraudulent credits.
   MD5 is legacy; newer integrations use SHA256 but the MD5 variant is
   still the most common.

2. **Round IDs and transaction types** — Pragmatic sends:
   - `bet` — debit (player places a bet)
   - `result` — credit (round settled)
   - `refund` — reverse an unsettled bet
   - `bonusWin` — free-round credit (different action code)
   - `promoWin` — jackpot win
   A single spin may generate up to 3 separate callbacks: bet → result →
   (optionally) bonusWin.

3. **Free rounds** — Pragmatic's free-round API is a separate REST service
   (`/IntegrationService/v3/http/FreeRoundsBonusAPI/`). The operator calls
   this API to award and cancel free-round bonuses. The wallet callbacks
   during free rounds use the same bet/result flow but with amount=0 for
   the bet and non-zero for results.

4. **Currency handling** — Pragmatic sends amounts as strings with
   currency-specific decimal precision. EUR amounts have 2 decimal places,
   but JPY amounts have 0 decimal places. Always use the currency's
   configured precision when converting.

5. **Token format** — The player token is a session token generated by
   the operator at launch. Pragmatic echoes it back on every callback.
   The operator must validate that the token is still active.

6. **Error codes** — Pragmatic expects numeric error codes:
   0 = OK, 1 = Invalid token, 2 = Invalid hash, 3 = Insufficient funds,
   4 = Unknown player, 6 = Transaction already exists

API reference: https://lobby.pragmaticplay.com/en/integration-guide/
"""

